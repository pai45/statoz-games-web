import fs from 'node:fs/promises';
import path from 'node:path';
import http from 'node:http';
import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const root=process.cwd(),require=createRequire(path.join(root,'package.json'));
const {chromium}=require('@playwright/test');
const out=path.join(root,'test-results/pitch-rush/aim');await fs.mkdir(out,{recursive:true});
const html=await fs.readFile(path.join(root,'public/embedded-games/pitch-rush/index.html'));
const server=http.createServer((req,res)=>{res.setHeader('Content-Type','text/html');res.end(html);});
await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
const browser=await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true,args:['--disable-gpu']});
const errors=[],report={};
try{
  const context=await browser.newContext({viewport:{width:844,height:390},hasTouch:true,isMobile:true});
  const page=await context.newPage();page.on('pageerror',e=>errors.push(e.message));
  await page.goto('http://127.0.0.1:'+server.address().port);await page.locator('#start').click();
  await page.waitForFunction(()=>window.__game?.state?.phase==='play');
  const start=await page.evaluate(()=>({tick:window.__game.state.tick,at:performance.now()}));
  await page.waitForTimeout(1100);
  const end=await page.evaluate(()=>({tick:window.__game.state.tick,at:performance.now()}));
  report.ticksPerSecond=(end.tick-start.tick)/((end.at-start.at)/1000);
  assert.ok(report.ticksPerSecond>35&&report.ticksPerSecond<53,'Expected roughly 45 simulation ticks per wall-clock second');
  const arrange=async()=>page.evaluate(()=>{
    const s=window.__game.state;s.phase='play';
    for(let t=0;t<2;t++)for(let i=0;i<11;i++)Object.assign(s.teams[t].players[i],{x:120+i*20,y:t===0?1000:200,vx:0,vy:0,slide:0,down:0,cooldown:9999,charge:0,charging:false});
    const p=s.teams[0].players[9];Object.assign(p,{x:400,y:850,cooldown:0,dirX:0,dirY:-1});
    s.teams[0].controlled=9;s.teams[0].prevMask=0;
    Object.assign(s.ball,{x:p.x,y:p.y,z:0,vx:0,vy:0,vz:0,owner:{team:0,idx:9}});
    window.__aimKicks=[];window.__game.transport.afterStep=state=>{if(state.events.some(e=>e.type==='kick'))window.__aimKicks.push({vx:state.ball.vx,vy:state.ball.vy,power:Math.hypot(state.ball.vx,state.ball.vy)});};
  });
  const stick=await page.locator('#stick').boundingBox(),attack=await page.locator('#btnKick').boundingBox();
  const cdp=await context.newCDPSession(page);
  const fire={x:attack.x+attack.width/2,y:attack.y+attack.height/2,id:2};
  const up={x:stick.x+stick.width/2,y:stick.y+10,id:1},right={x:stick.x+stick.width-8,y:stick.y+stick.height/2,id:1};
  await arrange();
  await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[up,fire]});
  await page.waitForFunction(()=>window.__game.state.teams[0].players[9].charging);
  await cdp.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[right,fire]});
  await page.waitForFunction(()=>window.__game.state.teams[0].players[9].kickAim?.x===1&&window.__game.state.teams[0].players[9].kickAim?.y===0);
  await page.screenshot({path:path.join(out,'aim-right.png')});
  await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[fire]});
  await page.waitForFunction(()=>window.__aimKicks.length>0);
  report.pass=await page.evaluate(()=>window.__aimKicks[0]);
  assert.ok(report.pass.vx>0&&Math.abs(report.pass.vy)<.001,'Released pass follows new rightward aim');
  await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});
  await arrange();
  await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[up,fire]});
  await page.waitForTimeout(1900);
  assert.equal(await page.evaluate(()=>window.__aimKicks.length),0,'Full power waits for release');
  assert.equal(await page.evaluate(()=>window.__game.state.teams[0].players[9].charging),true);
  await cdp.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[right,fire]});
  await page.waitForFunction(()=>window.__game.state.teams[0].players[9].kickAim.x===1);
  await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[fire]});
  await page.waitForFunction(()=>window.__aimKicks.length>0);
  report.shot=await page.evaluate(()=>window.__aimKicks[0]);
  assert.ok(report.shot.vx>0&&Math.abs(report.shot.vy)<.001);assert.ok(report.shot.power>report.pass.power);
  await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});
  assert.deepEqual(errors,[]);report.passed=true;report.errors=errors;
  await fs.writeFile(path.join(out,'report.json'),JSON.stringify(report,null,2));console.log(JSON.stringify(report));
}finally{
  server.close();const timeout=setTimeout(()=>process.exit(process.exitCode||0),10000);await browser.close();clearTimeout(timeout);
}
