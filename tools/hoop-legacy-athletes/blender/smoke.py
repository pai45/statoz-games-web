"""Phase 0 smoke asset: a box per bone, skinned to the full rig (joint ends blended 50/50 with the parent),
with one named morph target and a checker texture. Proves export -> pack -> load -> animate end to end.

blender -b --factory-startup -P smoke.py -- --rig build/rig.json --build build
"""
import math
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import common  # noqa: E402


def main():
    a = common.args()
    build = a["build"]
    rig = common.load_rig(a["rig"])
    common.reset_scene()
    arm = common.build_armature(rig)

    children = {}
    for b in rig["bones"]:
        if b["parent"]:
            children.setdefault(b["parent"], []).append(b)

    verts, faces, uvs, weights, inflate = [], [], [], [], []
    for b in rig["bones"]:
        head = b["bindPos"]
        kids = [c for c in children.get(b["name"], []) if sum((c["bindPos"][k] - head[k]) ** 2 for k in range(3)) > 1e-8]
        if kids:
            tail = kids[0]["bindPos"]
        else:
            # leaves: head up, hands/feet down along their parent segment
            par = rig["byName"][b["parent"]]["bindPos"]
            d = [head[k] - par[k] for k in range(3)]
            n = math.sqrt(sum(x * x for x in d)) or 1
            ln = 0.12 if b["name"] == "head" else 0.07
            tail = [head[k] + d[k] / n * ln for k in range(3)]
        axis = [tail[k] - head[k] for k in range(3)]
        ln = math.sqrt(sum(x * x for x in axis)) or 1
        ax = [x / ln for x in axis]
        # orthonormal frame around the segment
        ref = [0, 0, 1] if abs(ax[2]) < 0.9 else [1, 0, 0]
        u = [ax[1] * ref[2] - ax[2] * ref[1], ax[2] * ref[0] - ax[0] * ref[2], ax[0] * ref[1] - ax[1] * ref[0]]
        un = math.sqrt(sum(x * x for x in u))
        u = [x / un for x in u]
        w = [ax[1] * u[2] - ax[2] * u[1], ax[2] * u[0] - ax[0] * u[2], ax[0] * u[1] - ax[1] * u[0]]
        r = 0.03 if b["name"] in ("hips", "spine", "chest", "head") else 0.018
        base = len(verts)
        for end in (0, 1):
            for (su, sw) in ((-1, -1), (1, -1), (1, 1), (-1, 1)):
                t = 0.08 + 0.84 * end
                p = [head[k] + axis[k] * t + (u[k] * su + w[k] * sw) * r for k in range(3)]
                verts.append(p)
                uvs.append(((su + 1) * 0.25 + (sw + 1) * 0.125, end))
                inflate.append([(u[k] * su + w[k] * sw) * 0.01 for k in range(3)])
                if end == 0 and b["parent"]:
                    weights.append([(b["name"], 0.5), (b["parent"], 0.5)])
                else:
                    weights.append([(b["name"], 1.0)])
        quads = [(0, 1, 2, 3), (7, 6, 5, 4), (0, 4, 5, 1), (1, 5, 6, 2), (2, 6, 7, 3), (3, 7, 4, 0)]
        for q in quads:
            faces.append(tuple(base + i for i in q))

    obj = common.make_mesh("smoke", verts, faces, uvs)
    common.skin_to(obj, arm, weights)
    common.add_shape_keys(obj, {"smoke_inflate": inflate})
    common.export_glb(os.path.join(build, "lod0", "smoke.glb"), [obj], arm)

    # 256 px checker (color) to exercise the KTX2 path
    n = 256
    px = []
    for y in range(n):
        for x in range(n):
            c = ((x // 32) + (y // 32)) % 2
            px += [0.9, 0.45, 0.1, 1.0] if c else [0.12, 0.14, 0.2, 1.0]
    common.save_png(os.path.join(build, "textures", "lod0", "smoke_checker.png"), n, n, px)

    common.write_meta(build, "smoke", {
        "name": "smoke",
        "kind": "smoke",
        "slot": "smoke",
        "levels": {"lod0": {"glb": "lod0/smoke.glb", "textures": {"albedo": {"file": "textures/lod0/smoke_checker.png", "codec": "etc1s", "srgb": True}}}},
        "sources": ["tools/athletes/build/rig.json"],
        "license": "CC0-1.0 (generated by the toolchain)",
    })
    print("[smoke] ok", len(verts), "verts")


main()
